export function getHouse(id: string): HouseDef | undefined {
  return HOUSES.find((h) => h.id === id) ?? (id === TOURNAMENT_HOUSE.id ? TOURNAMENT_HOUSE : undefined);
}

export function getRival(id: string) {
  for (const house of [...HOUSES, TOURNAMENT_HOUSE]) {
    const fighter = house.fighters.find((f) => f.id === id);
    if (fighter) return { house, fighter };
  }
  const school = getSchoolCircuitFighter(id);
  if (school) {
    const house = getHouse(school.houseId);
    if (house) return { house, fighter: school.fighter };
  }
  return undefined;
}

export function houseBannerTex(id: string): string {
  return getHouse(id)?.bannerTex ?? "tile-banner-serpent";
}

export function houseCrowdTint(id: string): number {
  return getHouse(id)?.crowdTint ?? COLORS.serpentGreen;
}

export function houseTitleColor(id: string): string {
  return getHouse(id)?.titleColor ?? "#7ab8a4";
}

export function houseArenaLabel(id: string): string {
  return getHouse(id)?.arenaLabel ?? "ARENA OF THE SERPENT";
}

export function sortedHouses(): HouseDef[] {
  return [...HOUSES].sort((a, b) => a.difficulty - b.difficulty);
}

export function isTournamentId(id: string): boolean {
  return TOURNAMENT_HOUSE.fighters.some((f) => f.id === id);
}
